#!/usr/bin/env python3
"""Navigate resolved compiler intrinsics to truthful generated API references."""

import sys
import tempfile
from pathlib import Path
from urllib.parse import unquote, urlparse

from test_server import Client, document_position, initialize, offset_at


SOURCE = '''import * as json from "std/json";
import * as bytes from "std/bytes";
import { encode as save, decode as load } from "std/json";

fn calls(): void {
  const _ = json.encode(42);
  const _ = json.decode<int>(bytes.encodeUtf8("42"));
  const _ = save(true);
  const _ = load<bool>(bytes.encodeUtf8("true"));
  const limits = json.defaultLimits();
  const _ = json.encodeWithLimits("x", limits);
  const _ = json.decodeWithLimits<string>(bytes.encodeUtf8("\\"x\\""), limits);
}

fn encode(value: int): int { return value; }
fn ordinary(): int { return encode(1); }
fn shadow(save: (int)=>int): int { return save(3); }
'''


def file_path(uri):
    parsed = urlparse(uri)
    assert parsed.scheme == "file", uri
    path = unquote(parsed.path)
    if sys.platform == "win32" and len(path) > 2 and path[0] == "/" and path[2] == ":":
        path = path[1:]
    return Path(path)


def check(binary, directory):
    module = directory / "intrinsic API"
    module.mkdir()
    (module / "mmay.mod").write_text(
        'module "example/lsp-intrinsics"\nlanguage "0.1"\n', encoding="utf-8")
    path = module / "main.my"
    path.write_text(SOURCE, encoding="utf-8")
    client = Client(binary, directory)
    try:
        initialize(client, directory)
        assert client.open(path, SOURCE) == []
        for needle, expected_name in (
            ("encode(42)", "encode"), ("decode<int>", "decode"),
            ("save(true)", "encode"), ("load<bool>", "decode"),
            ("encodeWithLimits(\"x\"", "encodeWithLimits"),
            ("decodeWithLimits<string>", "decodeWithLimits"),
        ):
            params = document_position(path, SOURCE, needle)
            hover = client.request("textDocument/hover", params)
            assert "interface/signature only" in hover["contents"]["value"], hover
            assert f"fn {expected_name}<T>" in hover["contents"]["value"], hover
            definition = client.request("textDocument/definition", params)
            view = file_path(definition["uri"])
            assert ".mmay/lsp/stdlib/" in view.as_posix(), view
            assert view.as_posix().endswith("/std/json/intrinsics.my"), view
            view_source = view.read_text(encoding="utf-8")
            assert "implementation generated by compiler" in view_source, view_source
            start = offset_at(view_source, definition["range"]["start"])
            end = offset_at(view_source, definition["range"]["end"])
            assert view_source[start:end] == expected_name, definition

        # Intrinsic aliases retain the selected API identity; ordinary same-spelled
        # declarations and shadowing parameters keep their own real definitions.
        for needle in ("encode(1)", "save(3)"):
            definition = client.request("textDocument/definition",
                document_position(path, SOURCE, needle))
            assert definition["uri"] == path.as_uri(), definition

        params = document_position(path, SOURCE, "encode(42)")
        params["context"] = {"includeDeclaration": True}
        references = client.request("textDocument/references", params)
        assert len(references) == 3, references
        assert sum(reference["uri"] == path.as_uri() for reference in references) == 2
        definition = client.request("textDocument/definition", params)
        view = file_path(definition["uri"])
        view_source = view.read_text(encoding="utf-8")
        assert client.open(view, view_source) == []
        client.diagnostics(path.as_uri(), 1)
        view_params = {"textDocument": {"uri": view.as_uri()},
                       "position": definition["range"]["start"]}
        assert client.request("textDocument/definition", view_params) == definition
        hover = client.request("textDocument/hover", view_params)
        assert "fn encode<T>" in hover["contents"]["value"], hover
        view_params["context"] = {"includeDeclaration": False}
        references = client.request("textDocument/references", view_params)
        assert len(references) == 2 and all(
            reference["uri"] == path.as_uri() for reference in references), references

        broken = SOURCE.replace("encode(42)", 'encode("x", 42)')
        client.change(path, broken, 2)
        assert client.diagnostics(path.as_uri(), 2), "missing invalid intrinsic call error"
        client.diagnostics(view.as_uri(), 1)
        assert client.request("textDocument/hover",
            document_position(path, broken, "decode<int>")) is None
        client.change(path, SOURCE, 3)
        assert client.diagnostics(path.as_uri(), 3) == []
        assert client.diagnostics(view.as_uri(), 1) == []
        assert client.request("textDocument/definition",
            document_position(path, SOURCE, "encode(42)")) == definition

        # A retained generated view must not become the source graph selected by
        # workspace symbols after its project source closes.
        client.send("textDocument/didClose", {"textDocument": {"uri": path.as_uri()}})
        client.receive(lambda item: item.get("method") == "textDocument/publishDiagnostics"
                       and item["params"].get("uri") == path.as_uri())
        diagnostics = client.diagnostics(view.as_uri(), 1)
        assert len(diagnostics) == 1 and diagnostics[0]["severity"] == 3, diagnostics
        assert "Open a project source file" in diagnostics[0]["message"], diagnostics
        assert client.request("workspace/symbol", {"query": ""}) == []

        other_module = directory / "other module"
        other_module.mkdir()
        (other_module / "mmay.mod").write_text(
            'module "example/lsp-other"\nlanguage "0.1"\n', encoding="utf-8")
        other = other_module / "main.my"
        other_source = "fn otherAnswer(): int { return 43; }\n"
        other.write_text(other_source, encoding="utf-8")
        assert client.open(other, other_source) == []
        client.diagnostics(view.as_uri(), 1)
        symbols = client.request("workspace/symbol", {"query": "other"})
        assert len(symbols) == 1 and symbols[0]["name"] == "otherAnswer", symbols
        client.send("textDocument/didClose", {"textDocument": {"uri": other.as_uri()}})
        client.receive(lambda item: item.get("method") == "textDocument/publishDiagnostics"
                       and item["params"].get("uri") == other.as_uri())
        client.diagnostics(view.as_uri(), 1)
        assert client.request("workspace/symbol", {"query": ""}) == []
        assert client.open(path, SOURCE, 4) == []
        assert client.diagnostics(view.as_uri(), 1) == []
        assert client.request("textDocument/definition", view_params) == definition
        client.finish()
    finally:
        client.dispose()


def main():
    binary = Path(sys.argv[1]).resolve()
    with tempfile.TemporaryDirectory(prefix="mmay-lsp-intrinsics-") as temporary:
        check(binary, Path(temporary).resolve())
    print("mmay_lsp_intrinsics: ok")


if __name__ == "__main__":
    main()
